import { test, expect } from '@playwright/test';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../src/app.js';
import { grantSystemAdmin } from '../src/admin-access.js';

test('admin manages accounts, teams and members while ordinary accounts stay denied', async ({browser}) => {
  const directory=await mkdtemp(join(tmpdir(),'harness-admin-browser-'));
  const {app,db}=await createApp({dataDirectory:directory,rateLimits:false});
  const adminContext=await browser.newContext({viewport:{width:1440,height:1000}});
  const ownerContext=await browser.newContext();const memberContext=await browser.newContext();
  try {
    const origin=await app.listen({host:'127.0.0.1',port:0});
    async function register(context: typeof adminContext, username:string, displayName:string){
      const response=await context.request.post(`${origin}/api/v1/auth/register`,{data:{username,displayName,password:'pass1234'}});
      expect(response.status()).toBe(201);return response.json();
    }
    await register(adminContext,'deployer','系统管理员');grantSystemAdmin(db,'deployer');
    const owner=await register(ownerContext,'owner','项目负责人'),member=await register(memberContext,'worker','队友甲');
    const teamResponse=await ownerContext.request.post(`${origin}/api/v1/teams`,{data:{name:'产品探索团队'},headers:{'X-CSRF-Token':owner.csrfToken}});
    const team=await teamResponse.json();
    const invite=await (await ownerContext.request.post(`${origin}/api/v1/teams/${team.id}/invites`,{data:{},headers:{'X-CSRF-Token':owner.csrfToken}})).json();
    await memberContext.request.post(`${origin}/api/v1/teams/join`,{data:{token:invite.token},headers:{'X-CSRF-Token':member.csrfToken}});
    const page=await adminContext.newPage(),ordinary=await ownerContext.newPage();const errors:string[]=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('dialog',dialog=>void dialog.accept());
    await ordinary.goto(`${origin}/admin`);
    await expect(ordinary.getByRole('heading',{name:'无权访问系统管理'})).toBeVisible();
    await expect(ordinary.getByRole('button',{name:'系统管理',exact:true})).toHaveCount(0);
    expect((await ownerContext.request.get(`${origin}/api/v1/admin/overview`)).status()).toBe(403);
    await page.goto(`${origin}/admin`);
    await expect(page.getByRole('heading',{name:'系统管理',exact:true})).toBeVisible();
    await expect(page.getByRole('button',{name:'账号管理 →'})).toBeVisible();
    await mkdir('artifacts',{recursive:true});
    await page.screenshot({path:'artifacts/admin-overview.png',fullPage:true});
    await page.getByRole('button',{name:'账号管理',exact:true}).click();
    await page.getByLabel('搜索账号',{exact:true}).fill('worker');await page.getByRole('button',{name:'搜索',exact:true}).click();
    const account=page.getByRole('row').filter({has:page.getByText('队友甲',{exact:true})});
    await account.getByRole('button',{name:'停用账号'}).click();await expect(account.getByText('已停用',{exact:true})).toBeVisible();
    expect((await memberContext.request.get(`${origin}/api/v1/me`)).status()).toBe(401);
    await account.getByRole('button',{name:'启用账号'}).click();await expect(account.getByText('已启用',{exact:true})).toBeVisible();
    const login=await memberContext.request.post(`${origin}/api/v1/auth/login`,{data:{username:'worker',password:'pass1234'}});expect(login.status()).toBe(200);
    await account.getByRole('button',{name:'强制退出'}).click();await expect(page.getByRole('status')).toContainText('管理操作已保存');
    expect((await memberContext.request.get(`${origin}/api/v1/me`)).status()).toBe(401);
    await page.getByRole('button',{name:'团队管理',exact:true}).click();
    const teamRow=()=>page.getByRole('row').filter({has:page.getByText('产品探索团队',{exact:true})});
    await teamRow().getByRole('button',{name:'查看成员'}).click();
    const detail=page.locator('#admin-team-detail');
    await expect(detail.getByRole('heading',{name:'产品探索团队'})).toBeVisible();
    await detail.getByLabel('团队名称',{exact:true}).fill('新的团队名称');await detail.getByRole('button',{name:'保存名称'}).click();
    await expect(detail.getByRole('heading',{name:'新的团队名称'})).toBeVisible();
    const membership=detail.getByRole('row').filter({has:page.getByText('队友甲',{exact:true})});
    await membership.getByLabel('队友甲的团队权限',{exact:true}).selectOption('admin');
    await membership.getByRole('button',{name:'保存权限'}).click();await expect(membership.getByLabel('队友甲的团队权限',{exact:true})).toHaveValue('admin');
    await membership.getByRole('button',{name:'移除成员'}).click();await expect(membership).toHaveCount(0);
    const renamed=page.getByRole('row').filter({has:page.getByText('新的团队名称',{exact:true})});
    await renamed.getByRole('button',{name:'停用团队'}).click();await expect(renamed.getByText('已停用',{exact:true})).toBeVisible();
    expect((await ownerContext.request.get(`${origin}/api/v1/teams/${team.id}`)).status()).toBe(409);
    await renamed.getByRole('button',{name:'恢复团队'}).click();await expect(renamed.getByText('使用中',{exact:true})).toBeVisible();
    expect((await ownerContext.request.get(`${origin}/api/v1/teams/${team.id}`)).status()).toBe(200);
    await page.getByRole('button',{name:'操作记录',exact:true}).click();
    await expect(page.getByRole('cell',{name:'停用账号',exact:true})).toBeVisible();
    await expect(page.getByRole('cell',{name:'修改团队名称',exact:true})).toBeVisible();
    await page.setViewportSize({width:375,height:812});await page.emulateMedia({reducedMotion:'reduce'});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
    await page.screenshot({path:'artifacts/admin-mobile.png',fullPage:true});
    expect(errors).toEqual([]);
  } finally {await adminContext.close();await ownerContext.close();await memberContext.close();await app.close();await rm(directory,{recursive:true,force:true});}
});
